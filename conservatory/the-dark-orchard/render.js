function compile(gl, type, src) {
  const s = gl.createShader(type);
  gl.shaderSource(s, src); gl.compileShader(s);
  if (!gl.getShaderParameter(s, gl.COMPILE_STATUS)) {
    const log = gl.getShaderInfoLog(s);
    const numbered = src.split('\n').map((l, i) => (i + 1) + ': ' + l).join('\n');
    throw new Error('shader: ' + log + '\n' + numbered.slice(0, 2600));
  }
  return s;
}
function program(gl, vs, fs) {
  const p = gl.createProgram();
  gl.attachShader(p, compile(gl, gl.VERTEX_SHADER, vs));
  gl.attachShader(p, compile(gl, gl.FRAGMENT_SHADER, fs));
  gl.linkProgram(p);
  if (!gl.getProgramParameter(p, gl.LINK_STATUS)) throw new Error('link: ' + gl.getProgramInfoLog(p));
  return p;
}
function uniforms(gl, p) {
  const u = {};
  const n = gl.getProgramParameter(p, gl.ACTIVE_UNIFORMS);
  for (let i = 0; i < n; i++) {
    const info = gl.getActiveUniform(p, i);
    const name = info.name.replace(/\[0\]$/, '');
    u[name] = gl.getUniformLocation(p, info.name);
  }
  return u;
}

DO.Renderer = class {
  constructor(canvas, caps, groups, refl, sdfSrc, beamSrc) {
    const gl = canvas.getContext('webgl2', { antialias: false, alpha: false, depth: false, powerPreference: 'high-performance' });
    if (!gl) throw new Error('no WebGL2');
    if (!gl.getExtension('EXT_color_buffer_float')) throw new Error('no float render targets');
    this.gl = gl; this.canvas = canvas;
    this.nCap = caps.length; this.nGroup = groups.length;
    this.refl = new Float32Array(refl);

    this.pMarch = program(gl, DO.VS, DO.marchFS(sdfSrc, beamSrc, this.nCap, this.nGroup));
    this.pBright = program(gl, DO.VS, DO.brightFS);
    this.pBlur = program(gl, DO.VS, DO.blurFS);
    this.pComp = program(gl, DO.VS, DO.compositeFS);
    this.uMarch = uniforms(gl, this.pMarch);
    this.uBright = uniforms(gl, this.pBright);
    this.uBlur = uniforms(gl, this.pBlur);
    this.uComp = uniforms(gl, this.pComp);

    this.vao = gl.createVertexArray();

    /* the scene, packed once — setCaps() re-uploads when a post moves */
    this.capA = new Float32Array(this.nCap * 4);
    this.capB = new Float32Array(this.nCap * 4);
    this.grp = new Float32Array(this.nGroup * 4);
    this.rng = new Float32Array(this.nGroup * 4);
    this.setCaps(caps, groups);

    this.ch = new Float32Array(8 * 4);      // (age, halfWidth, amp, -) per chirp
    this.cent = new Float32Array(24);       // uploaded as 6 vec4s
    this.refl4 = new Float32Array(8);
    this.refl4.set(this.refl.subarray(0, Math.min(6, this.refl.length)));
    this.probeDir = new Float32Array(16 * 4);

    this.fbo = { scene: null, a: null, b: null, probe: null };
    this.w = 0; this.h = 0;
    this._makeProbe();
  }

  setCaps(caps, groups) {
    for (let i = 0; i < caps.length; i++) {
      const r = caps[i];
      this.capA[i * 4] = r[0]; this.capA[i * 4 + 1] = r[1]; this.capA[i * 4 + 2] = r[2]; this.capA[i * 4 + 3] = r[6];
      this.capB[i * 4] = r[3]; this.capB[i * 4 + 1] = r[4]; this.capB[i * 4 + 2] = r[5]; this.capB[i * 4 + 3] = r[7];
    }
    for (let g = 0; g < groups.length; g++) {
      const G = groups[g];
      this.grp[g * 4] = G.cx; this.grp[g * 4 + 1] = G.cy; this.grp[g * 4 + 2] = G.cz; this.grp[g * 4 + 3] = G.rad;
      this.rng[g * 4] = G.from; this.rng[g * 4 + 1] = G.to;
    }
  }

  _tex(w, h, internal, filter) {
    const gl = this.gl, t = gl.createTexture();
    gl.bindTexture(gl.TEXTURE_2D, t);
    gl.texStorage2D(gl.TEXTURE_2D, 1, internal, w, h);
    gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MIN_FILTER, filter);
    gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MAG_FILTER, filter);
    gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_WRAP_S, gl.CLAMP_TO_EDGE);
    gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_WRAP_T, gl.CLAMP_TO_EDGE);
    return t;
  }
  _target(w, h, internal, filter) {
    const gl = this.gl;
    const tex = this._tex(w, h, internal, filter);
    const fb = gl.createFramebuffer();
    gl.bindFramebuffer(gl.FRAMEBUFFER, fb);
    gl.framebufferTexture2D(gl.FRAMEBUFFER, gl.COLOR_ATTACHMENT0, gl.TEXTURE_2D, tex, 0);
    gl.bindFramebuffer(gl.FRAMEBUFFER, null);
    return { fb, tex, w, h };
  }
  _makeProbe() {
    /* 32 rays, marched on the GPU, read back as floats so the page can hold
       the shader's own distance field against the JS one every second */
    this.probe = this._target(16, 1, this.gl.RGBA32F, this.gl.NEAREST);
    this.probeBuf = new Float32Array(16 * 4);
  }

  resize(w, h) {
    if (w === this.w && h === this.h) return;
    const gl = this.gl;
    for (const k of ['scene', 'a', 'b']) if (this.fbo[k]) { gl.deleteFramebuffer(this.fbo[k].fb); gl.deleteTexture(this.fbo[k].tex); }
    this.w = w; this.h = h;
    const qw = Math.max(2, w >> 2), qh = Math.max(2, h >> 2);
    this.fbo.scene = this._target(w, h, gl.RGBA16F, gl.LINEAR);
    this.fbo.a = this._target(qw, qh, gl.RGBA16F, gl.LINEAR);
    this.fbo.b = this._target(qw, qh, gl.RGBA16F, gl.LINEAR);
  }

  _bindMarch(S, probe) {
    const gl = this.gl, u = this.uMarch;
    gl.useProgram(this.pMarch);
    gl.uniform4fv(u.uCapA, this.capA);
    gl.uniform4fv(u.uCapB, this.capB);
    gl.uniform4fv(u.uGroup, this.grp);
    gl.uniform4fv(u.uRange, this.rng);
    gl.uniform3fv(u.uMoth, S.moth);
    gl.uniform3fv(u.uEye, S.eye);
    gl.uniform3fv(u.uFwd, S.fwd);
    gl.uniform3fv(u.uRight, S.right);
    gl.uniform3fv(u.uUp, S.up);
    gl.uniform1f(u.uTanHalf, S.tanHalf);
    gl.uniform4fv(u.uCh, this.ch);
    gl.uniform1i(u.uNCh, S.nCh);
    gl.uniform1f(u.uInvHalfPath, S.invHalfPath);
    gl.uniform1f(u.uAlpha2, S.alpha2);
    gl.uniform1f(u.uKa, S.ka);
    gl.uniform1f(u.uTau, S.tau);
    gl.uniform1f(u.uGain, S.gain);
    gl.uniform1f(u.uRing, S.ring);
    gl.uniform4fv(u.uRefl, this.refl4);
    gl.uniform4fv(u.uCent, this.cent);
    gl.uniform1f(u.uCentMax, S.centMax);
    gl.uniform1f(u.uMothFlick, S.mothFlick);
    gl.uniform1f(u.uProbe, probe ? 1 : 0);
    gl.uniform2f(u.uRes, probe ? 16 : this.w, probe ? 1 : this.h);
  }

  /* Ask the GPU to march 32 given directions and hand the distances back.
     The page compares them with orchard.mjs's own march(). */
  probeDistances(S, dirs) {
    const gl = this.gl;
    const n = Math.min(16, Math.floor(dirs.length / 3));
    this.probeDir.fill(0);
    for (let i = 0; i < n; i++) {
      this.probeDir[i * 4] = dirs[i * 3];
      this.probeDir[i * 4 + 1] = dirs[i * 3 + 1];
      this.probeDir[i * 4 + 2] = dirs[i * 3 + 2];
    }
    gl.bindFramebuffer(gl.FRAMEBUFFER, this.probe.fb);
    gl.viewport(0, 0, 16, 1);
    gl.bindVertexArray(this.vao);
    this._bindMarch(S, true);
    gl.uniform4fv(this.uMarch.uProbeDir, this.probeDir);
    gl.drawArrays(gl.TRIANGLES, 0, 3);
    gl.readPixels(0, 0, 16, 1, gl.RGBA, gl.FLOAT, this.probeBuf);
    gl.bindFramebuffer(gl.FRAMEBUFFER, null);
    const out = [];
    for (let i = 0; i < n; i++) out.push({ t: this.probeBuf[i * 4], mat: Math.round(this.probeBuf[i * 4 + 1]) });
    return out;
  }

  draw(S) {
    const gl = this.gl;
    gl.bindVertexArray(this.vao);
    gl.disable(gl.DEPTH_TEST);
    gl.disable(gl.BLEND);

    gl.bindFramebuffer(gl.FRAMEBUFFER, this.fbo.scene.fb);
    gl.viewport(0, 0, this.w, this.h);
    this._bindMarch(S, false);
    gl.uniform2f(this.uMarch.uRes, this.w, this.h);
    gl.drawArrays(gl.TRIANGLES, 0, 3);

    /* bright pass */
    const q = this.fbo.a;
    gl.bindFramebuffer(gl.FRAMEBUFFER, q.fb);
    gl.viewport(0, 0, q.w, q.h);
    gl.useProgram(this.pBright);
    gl.activeTexture(gl.TEXTURE0); gl.bindTexture(gl.TEXTURE_2D, this.fbo.scene.tex);
    gl.uniform1i(this.uBright.uSrc, 0);
    gl.uniform2f(this.uBright.uSrcTexel, 1 / this.w, 1 / this.h);
    gl.uniform1f(this.uBright.uThresh, S.bloomThresh);
    gl.drawArrays(gl.TRIANGLES, 0, 3);

    /* two separable passes */
    for (const [src, dst, dir] of [[this.fbo.a, this.fbo.b, [1, 0]], [this.fbo.b, this.fbo.a, [0, 1]]]) {
      gl.bindFramebuffer(gl.FRAMEBUFFER, dst.fb);
      gl.viewport(0, 0, dst.w, dst.h);
      gl.useProgram(this.pBlur);
      gl.activeTexture(gl.TEXTURE0); gl.bindTexture(gl.TEXTURE_2D, src.tex);
      gl.uniform1i(this.uBlur.uSrc, 0);
      gl.uniform2f(this.uBlur.uTexel, 1 / dst.w, 1 / dst.h);
      gl.uniform2f(this.uBlur.uDir, dir[0], dir[1]);
      gl.drawArrays(gl.TRIANGLES, 0, 3);
    }

    gl.bindFramebuffer(gl.FRAMEBUFFER, null);
    gl.viewport(0, 0, this.canvas.width, this.canvas.height);
    gl.useProgram(this.pComp);
    gl.activeTexture(gl.TEXTURE0); gl.bindTexture(gl.TEXTURE_2D, this.fbo.scene.tex);
    gl.activeTexture(gl.TEXTURE1); gl.bindTexture(gl.TEXTURE_2D, this.fbo.a.tex);
    gl.uniform1i(this.uComp.uScene, 0);
    gl.uniform1i(this.uComp.uBloom, 1);
    gl.uniform2f(this.uComp.uSceneTexel, 1 / this.canvas.width, 1 / this.canvas.height);
    gl.uniform2f(this.uComp.uBloomTexel, 1 / this.canvas.width, 1 / this.canvas.height);
    gl.uniform1f(this.uComp.uBloomAmt, S.bloom);
    gl.uniform1f(this.uComp.uVig, 0.32);
    gl.drawArrays(gl.TRIANGLES, 0, 3);
  }
};
