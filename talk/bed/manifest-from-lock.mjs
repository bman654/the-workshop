#!/usr/bin/env node
/* ============================================================================
   THE MANIFEST GENERATOR — `node manifest-from-lock.mjs`
   talk/projection-room.cues.lock.json  →  talk/bed/manifest.json

   This is the step that makes CH4's on-camera claim literally true:
   "The score playing under this film right now was computed from this film's
   own cue sheet. Move a cue, re-render — and it lands on the new time, bit
   for bit, every run."

   Every time in the emitted manifest is COPIED from the cue lock (which was
   itself copied from the rendered word timestamps — invariant 4) and mapped
   onto the WALL-CLOCK film timeline:

     wallStart(chapter i) = filmOffsetMs(i)  +  i * interChapterGapMs

   because the cue lock's offsets are the RAIL convention (cumulative chapter
   durations, no gaps) while real playback inserts a fixed 2000 ms
   auto-advance hold between chapters (talk/showing.js:392). The bed is ONE
   continuous track under the whole film, so it lives on the wall clock.
   This is the reconciliation T5.1 flagged for T4.2.

   Deterministic: same lock in → byte-identical manifest out. No randomness,
   no clock reads. Musical pickup lengths (a riser leading INTO an anchored
   peak, echo spacing, note spreads inside a locked window) are composition
   constants in compose.mjs — the ANCHORS all come from here.
   ============================================================================ */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const LOCK_PATH = join(HERE, '..', 'projection-room.cues.lock.json');
const OUT_PATH = join(HERE, 'manifest.json');

const lock = JSON.parse(readFileSync(LOCK_PATH, 'utf8'));
const GAP_MS = lock.bedManifestInputs.interChapterGapMs;   /* 2000 (showing.js:392) */

/* ---- wall-clock chapter map ------------------------------------------------ */
const chapters = lock.chapterList.map((ch, i) => ({
  id: ch.id,
  title: ch.title,
  wallStartMs: ch.filmOffsetMs + i * GAP_MS,
  wallEndMs: ch.filmOffsetMs + ch.durationMs + i * GAP_MS,
}));
const wall = Object.fromEntries(chapters.map(c => [c.id, c.wallStartMs]));

/* ---- cue lookup (audit.cues: {cue,side,ms}) -------------------------------- */
const cueRows = lock.audit.cues;
function cueWall(prefix){
  const hit = cueRows.find(c => c.cue === prefix || c.cue.startsWith(prefix + ' '));
  if (!hit) throw new Error('cue not found in lock: ' + prefix);
  if (!(hit.side in wall)) throw new Error('cue ' + prefix + ' is not on a film chapter: ' + hit.side);
  return wall[hit.side] + hit.ms;
}
const rows = (chPrefix, n) =>
  Array.from({ length: n }, (_, i) => cueWall(`${chPrefix}.rows[${i}]`));

/* ---- the CH4 crescendo window (bedManifestInputs, rail → wall) ------------- */
const cw = lock.bedManifestInputs.crescendoWindow;
const p04aIdx = chapters.findIndex(c => c.id === 'p04a');
const railToWall4a = ms => ms + p04aIdx * GAP_MS;             /* p04a rail-abs → wall */
const swellAnnounce = railToWall4a(cw.crescendoWordStartAbsMs); /* the word "crescendo" */
const swellGapStart = railToWall4a(cw.p04aEndAbsMs);            /* p04a audio ends */
const swellResolve  = railToWall4a(cw.p04bFirstWordAbsMs) + GAP_MS; /* "Right on cue" —
     p04bFirstWordAbsMs is rail; p04b sits one more gap out than p04a's rail frame */
/* peak 40% into the true-silence gap: crest exposed, decay audible under "Right" */
const swellPeak = swellGapStart + Math.round(0.4 * (swellResolve - swellGapStart));

/* ---- ducking: the per-chapter VO spans, wall clock ------------------------- */
const duckSpans = lock.bedManifestInputs.duckWindowsAbsMs.map(w => {
  const i = chapters.findIndex(c => c.id === w.id);
  return [w.span[0] + i * GAP_MS, w.span[1] + i * GAP_MS];
});

/* ---- the ending (CH6 door cues own the cadence + fade) --------------------- */
const endDoor = cueWall('CH6.endDoorT');
const endOpen = cueWall('CH6.endOpenT');
const filmEnd = chapters[chapters.length - 1].wallEndMs;   /* last voice sample */
const fadeStartMs = endOpen;                    /* the door opens; the bed exhales */
const fadeEndMs = fadeStartMs + 4200;           /* past filmEnd: the tail rides the held end card */
const totalMs = fadeEndMs + 1200;               /* true silence to finish the file */

const manifest = {
  _comment: 'GENERATED by talk/bed/manifest-from-lock.mjs from talk/projection-room.cues.lock.json '
    + '— do not hand-edit; move a cue, regenerate, re-render. All times ms on the WALL CLOCK '
    + '(rail offsets + i*interChapterGapMs auto-advance holds).',
  seed: 4207,                                   /* film 4, workstream 7 */
  sampleRate: 44100,
  interChapterGapMs: GAP_MS,
  totalMs,
  filmEndMs: filmEnd,
  chapters,
  duckSpans,
  duckLevel: 0.44,
  swell: {
    announceMs: swellAnnounce,   /* VO: "…here comes a crescendo" — the bed answers on the word */
    gapStartMs: swellGapStart,   /* narration track ENDS: the bed is alone */
    peakMs: swellPeak,           /* the crest, wholly inside the true-VO gap */
    resolveMs: swellResolve,     /* p04b "Right on cue" — the bloom decays under it */
  },
  fadeStartMs,
  fadeEndMs,
  marks: {
    /* CH1 — the six preflight checks: the film's germ motif */
    ch1Rows: rows('CH1', 6),
    ch1Cut: cueWall('CH1.cutT'),
    /* CH2 — the machine wakes */
    ch2Rows: rows('CH2', 3),
    /* CH3 — the captions are listening */
    ch3Sunset: cueWall('CH3.sunsetT'),
    ch3Steps: [cueWall('CH3.reveal'), cueWall('CH3.bytesHot'),
               cueWall('CH3.annA'), cueWall('CH3.annB')],
    ch3Hide: cueWall('CH3.hide'),
    /* CH4 — one clock */
    ch4Looking: cueWall('CH4.lookingT'),
    ch4Docks: cueWall('CH4.docksReveal'),
    ch4BrokenCut: cueWall('CH4.brokenCutT'),
    ch4FixedLand: cueWall('CH4.fixedLandT'),
    ch4Files: [cueWall('CH4.filesReveal'), cueWall('CH4.filesHide')],
    ch4Score: cueWall('CH4.scoreT'),
    ch4bRight: cueWall('CH4.p04b cue Right'),   /* side=p04b → cueWall already on the wall */
    ch4bFiles: cueWall('CH4.p04b cue files'),
    /* CH5 — draft two */
    ch5SeedLit: [cueWall('CH5.seedLit1'), cueWall('CH5.seedLit2')],
    ch5Shots: Array.from({ length: 6 }, (_, i) => cueWall(`CH5.shots[${i}]`)),
    ch5Push: cueWall('CH5.pushReveal'),
    ch5Crits: [cueWall('CH5.crit2Lit'), cueWall('CH5.crit3Lit')],
    ch5Revise: cueWall('CH5.reviseAt'),
    ch5Loop: cueWall('CH5.loopAt'),
    ch5Spec: cueWall('CH5.specReveal'),
    ch5Heard: cueWall('CH5.heardAt'),
    ch5Read: cueWall('CH5.readAt'),
    ch5Slate: cueWall('CH5.slateReveal'),
    ch5Stamp: cueWall('CH5.stampAt'),          /* "two" — the slate stamps DRAFT 2 */
    /* CH6 — press record */
    ch6Recap: [cueWall('CH6.rc1'), cueWall('CH6.rc2'), cueWall('CH6.rc3')],
    ch6Human: cueWall('CH6.rcHuman'),
    ch6PfGreen: cueWall('CH6.pfGreenT'),
    ch6PfWaits: cueWall('CH6.pfWaitsT'),
    ch6Clicks: [cueWall('CH6.clickStart'), cueWall('CH6.clickArm'), cueWall('CH6.clickStop')],
    ch6Trim: [cueWall('CH6.trimCutT'), cueWall('CH6.trimDropT')],
    ch6MirrorDeep: cueWall('CH6.mirrorDeepT'),
    ch6EndDoor: endDoor,
    ch6EndOpen: endOpen,
  },
};

/* wall-clock ordering sanity: chapters strictly sequential, swell inside the gap */
for (let i = 1; i < chapters.length; i++)
  if (chapters[i].wallStartMs !== chapters[i - 1].wallEndMs + GAP_MS)
    throw new Error('chapter wall map broken at ' + chapters[i].id);
if (!(swellGapStart < swellPeak && swellPeak < swellResolve))
  throw new Error('swell peak not inside the true-VO gap');

writeFileSync(OUT_PATH, JSON.stringify(manifest, null, 2) + '\n');
console.log('wrote ' + OUT_PATH);
console.log('  film (wall) ' + (filmEnd / 1000).toFixed(3) + ' s · bed total ' + (totalMs / 1000).toFixed(3) + ' s');
console.log('  swell announce ' + swellAnnounce + ' · gap ' + swellGapStart + ' → peak ' + swellPeak + ' → resolve ' + swellResolve);
